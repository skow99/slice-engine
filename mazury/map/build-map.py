"""Export the Niegocin game map from Giżycko BDOT10k GeoPackages and elevation rasters."""
import argparse
from contextlib import closing
import json
import math
from pathlib import Path
import sqlite3

import numpy as np
from PIL import Image
import rasterio
from rasterio.features import rasterize
from rasterio.transform import from_origin
from rasterio.warp import Resampling, reproject
from scipy.ndimage import distance_transform_edt, gaussian_filter
import shapely

WEST, NORTH = 677400, 690500
CELL = 3
WIDTH, HEIGHT = 3400, 3700
CRS = "EPSG:2180"
TRANSFORM = from_origin(WEST, NORTH, CELL, CELL)
EXTENT = shapely.box(WEST, NORTH - HEIGHT * CELL, WEST + WIDTH * CELL, NORTH)
WATER = 20
ELEVATION_ORIGIN = 80
ELEVATION_STEP = 0.5


def features(directory, layer, *fields):
    path, = directory.glob(f"*__OT_{layer}.gpkg")
    with closing(sqlite3.connect(path)) as database:
        table, column = database.execute(
            "SELECT table_name, column_name FROM gpkg_geometry_columns"
        ).fetchone()
        index = f"rtree_{table}_{column}"
        west, south, east, north = EXTENT.bounds
        rows = database.execute(
            f'SELECT {", ".join([column, *fields])} FROM "{table}" '
            f'WHERE id IN (SELECT id FROM "{index}" WHERE minx <= ? AND maxx >= ? AND miny <= ? AND maxy >= ?)',
            (east, west, north, south),
        )
        for blob, *attributes in rows:
            envelope_size = {0: 0, 1: 32, 2: 48, 3: 48, 4: 64}[(blob[3] >> 1) & 7]
            geometry = shapely.from_wkb(blob[8 + envelope_size:])
            if not geometry.is_valid:
                geometry = shapely.make_valid(geometry)
            if not geometry.is_empty:
                yield geometry, attributes


def elevations(national):
    samples = np.full((HEIGHT, WIDTH), np.nan, dtype=np.float32)
    with rasterio.open(national) as dataset:
        reproject(
            dataset.read(1), samples, src_transform=dataset.transform, src_crs=CRS,
            src_nodata=0, dst_transform=TRANSFORM, dst_crs=CRS, dst_nodata=np.nan,
            resampling=Resampling.bilinear,
        )
    if not np.isfinite(samples).all():
        raise ValueError("The elevation raster leaves holes in the export extent")
    return gaussian_filter(samples, 1.0)


def world_point(x, y):
    return [round((x - WEST) / CELL, 3), round((NORTH - y) / CELL, 3)]


def export_buildings(topography, output, water):
    shore = shapely.union_all([g for g, _ in water if g.area >= 16000]).buffer(720)
    shapely.prepare(shore)
    rows = []
    for geometry, [floors] in features(topography, "BUBD_A", "LICZBAKONDYGNACJI"):
        center = geometry.representative_point()
        if geometry.area < 10 or not shore.covers(center):
            continue
        rectangle = geometry.minimum_rotated_rectangle
        if rectangle.geom_type != "Polygon":
            continue
        points = list(rectangle.exterior.coords)
        (a, b), (c, d) = sorted(
            zip(points[:2], points[1:3]),
            key=lambda pair: math.dist(*pair), reverse=True,
        )
        rows.append([
            round(center.x - WEST, 1), round(NORTH - center.y, 1),
            round(math.dist(a, b), 1), round(math.dist(c, d), 1),
            round(math.degrees(math.atan2(a[1] - b[1], b[0] - a[0]))) % 180,
            max(1, min(6, math.ceil(floors or 1))),
        ])
    rows.sort(key=lambda row: (-row[2] * row[3], row[0], row[1]))
    (output / "buildings.js").write_text(
        "// Generated by build-map.py from BDOT10k. X, Y, length, width in survey metres, heading in degrees, floors.\n"
        "export const buildings = [\n"
        + "".join(json.dumps(row, separators=(",", ":")) + ",\n" for row in rows)
        + "];\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("topography", type=Path, help="Directory of extracted Giżycko BDOT10k GeoPackages")
    parser.add_argument("elevation", type=Path, help="Geoportal NMT grid in EPSG:2180")
    args = parser.parse_args()
    topography = args.topography
    output = Path(__file__).parent
    shapes = []

    def add(layer, code):
        shapes.extend((geometry, code) for geometry, _ in features(topography, layer))

    woodland = {"liściasty": 1, "iglasty": 2, "mieszany": 3}
    shapes.extend((geometry, woodland.get(kind, 3)) for geometry, [kind] in features(topography, "PTLZ_A", "KATEGORIA"))
    for geometry, [kind] in features(topography, "PTTR_A", "RODZAJ"):
        if kind == "uprawa na gruntach ornych":
            variant = int(geometry.centroid.x * 0.29 + geometry.centroid.y * 0.51) % 3
            shapes.append((geometry, 12 + variant))
    for layer, code in [("PTZB_A", 5), ("PTGN_A", 6), ("PTSO_A", 7), ("PTRK_A", 8), ("PTUT_A", 11)]:
        add(layer, code)
    for geometry, [width, position] in features(topography, "SKDR_L", "SZEROKOSCNAWIERZCHNI", "POLOZENIE"):
        if position != "pod powierzchnią terenu":
            shapes.append((geometry.buffer(max(1.5, min(float(width or 4), 10) / 2), cap_style="flat"), 9))
    water = list(features(topography, "PTWP_A", "NAZWA", "POCZATEKWERSJIOBIEKTU"))
    export_buildings(topography, output, water)
    shapes.extend((geometry, WATER) for geometry, _ in water)
    # Footprints are a separate display layer baked into the class raster.
    add("BUBD_A", 10)

    cover = rasterize(shapes, out_shape=(HEIGHT, WIDTH), transform=TRANSFORM, dtype=np.uint8)
    wet = rasterize([(g, 1) for g, _ in water], out_shape=cover.shape, transform=TRANSFORM, dtype=np.uint8).astype(bool)
    cover[wet] = WATER
    meters = elevations(args.elevation)
    elevation_origin = min(ELEVATION_ORIGIN, math.floor(float(meters.min())))
    elevation_step = max(ELEVATION_STEP, math.ceil((float(meters.max()) - elevation_origin) * 2 / 255) / 2)
    elevation = np.rint((meters - elevation_origin) / elevation_step).astype(np.uint8)
    distance = np.minimum(255, distance_transform_edt(wet) + distance_transform_edt(~wet)).astype(np.uint8)
    Image.fromarray(np.stack([cover, elevation, distance], axis=-1)).save(output / "terrain.png", optimize=True)

    main_lake, date = next((geometry, date) for geometry, [name, date] in water if name == "Niegocin")
    lakes = []
    for geometry, [name, _] in water:
        if geometry.area < 16000:
            continue
        clipped = geometry.intersection(EXTENT)
        polygons = [clipped] if clipped.geom_type == "Polygon" else getattr(clipped, "geoms", [])
        for polygon in polygons:
            if polygon.geom_type != "Polygon" or polygon.is_empty:
                continue
            lakes.append({
                "name": name,
                "rings": [[world_point(x, y) for x, y in ring.coords] for ring in (polygon.exterior, *polygon.interiors)],
            })
    wanted = {"Giżycko", "Wilkasy", "Bystry", "Strzelce", "Rydzewo", "Bogaczewo", "Grajwo", "Ruda", "Kleszczewo-Osada"}
    towns = {}
    for geometry, [name] in features(topography, "ADMS_P", "NAZWA"):
        if name in wanted and EXTENT.covers(geometry):
            towns[name] = world_point(geometry.x, geometry.y)
    metadata = {
        "width": WIDTH, "height": HEIGHT, "metersPerPixel": CELL,
        "origin": [WEST, NORTH], "crs": CRS,
        "elevationOrigin": elevation_origin, "elevationStep": elevation_step,
        "landElevationRange": [round(float(meters[~wet].min()), 1), round(float(meters[~wet].max()), 1)],
        "lakeArea": round(main_lake.area), "surveyDate": date[:10],
        "towns": towns, "lakes": lakes,
    }
    (output / "survey.js").write_text(
        "// Generated by build-map.py. Mapped water rings are in world pixels.\n"
        "export const survey = " + json.dumps(metadata, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )
    print({key: value for key, value in metadata.items() if key != "lakes"})


if __name__ == "__main__":
    main()
